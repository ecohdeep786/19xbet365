export function GameCategoryPage({ kind }: { kind: GameCategoryKind }) {
  const { games, loading } = useData();
  const config = CONFIG[kind];
  const [query, setQuery] = useState("");
  const [chip, setChip] = useState("all");

  const base = useMemo(() => {
    if (config.ids) return config.ids.map((id) => games.find((game) => game.id === id)).filter(Boolean) as typeof games;
    return games.filter((game) => config.categories?.includes(game.category));
  }, [games, config]);

  const filtered = useMemo(() => {
    let list = base;
    if (chip === "popular") list = list.filter((game) => game.featured || game.players > 3000);
    if (query.trim()) {
      const q = query.toLowerCase();
      list = list.filter((game) => [game.name, game.tagline, game.category].some((value) => value.toLowerCase().includes(q)));
    }
    return [...list].sort((a, b) => Number(b.featured) - Number(a.featured) || b.players - a.players);
  }, [base, chip, query]);

  if (loading) return <div className="page-shell"><Skeleton className="sk-line" /><Skeleton className="sk-line" /><Skeleton className="sk-line" /></div>;

  return (
    <div className="category-page">
      <div className="page-hero casino-hero">
        <div className="casino-hero-glow" />
        <div className="page-shell page-hero-inner">
          <div>
            <span className="eyebrow"><Sparkles size={13} /> {config.kicker}</span>
            <h1>{config.title}</h1>
            <p>{config.body}</p>
            <div className="page-hero-stats inline-stats">
              <div><strong>{number(base.length)}</strong><span>titles</span></div>
              <div><strong>{number(base.reduce((sum, game) => sum + game.players, 0))}</strong><span>in lobby</span></div>
              <div><strong>19X</strong><span>server RNG</span></div>
            </div>
          </div>
          {base[0] && <Link to={`/game/${base[0].id}`} className="featured-game-card"><GameArt game={base[0]} /><div className="featured-game-copy"><span className="featured-kicker">PLAY NOW</span><h2>{base[0].name}</h2><p>{base[0].tagline}</p><span className="featured-play">Open game <ArrowRight size={16} /></span></div></Link>}
        </div>
      </div>
      <div className="page-shell">
        <div className="category-toolbar">
          <div className="category-search"><Search size={16} /><Input value={query} onChange={(event) => setQuery(event.target.value)} placeholder={`Search ${config.kicker.toLowerCase()}`} aria-label={`Search ${config.kicker}`} /></div>
          <div className="filter-chips">
            <button className={`filter-chip ${chip === "all" ? "active" : ""}`} onClick={() => setChip("all")}>All</button>
            <button className={`filter-chip ${chip === "popular" ? "active" : ""}`} onClick={() => setChip("popular")}>Popular</button>
          </div>
        </div>
        <div className="lobby-head"><div><span className="eyebrow">{config.kicker}</span><h2>{filtered.length} {filtered.length === 1 ? "title" : "titles"}</h2></div></div>
        {filtered.length ? (
          <div className="game-grid lobby-grid">{filtered.map((game) => <GameCard key={game.id} game={game} size="md" />)}</div>
        ) : (
          <div className="panel"><p className="empty-copy">No games match this view. Try another search.</p></div>
        )}
        <section className="panel category-note">
          <strong>Original 19X games, not provider copies.</strong>
          <p>Every title here is built and settled by the 19X server. Results are recorded in your game activity. Coins have no cash value. These are RNG games; no live dealer feed or certified third-party provider is connected.</p>
        </section>
      </div>
    </div>
  );
}
